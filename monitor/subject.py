"""О чём публикация по существу и чья это зона ответственности (сборка 2026.10.23).

Урок 21–23.10 (ЖК «Виктория», Авиаторов Балтики 9к2): подростки забрасывают яйцами дверь квартиры пенсионеров.
Наш ЖК и наш адрес названы, тон негативный, — и Радар четыре раза поднимал P2 «ответить от лица УК», хотя УК в истории
нет: это хулиганство, им занимается полиция. Название ЖК в тексте — не довод «спросят с УК».

Правило: если суть — действия третьих лиц (хулиганство, вандализм, травля, конфликт соседей) и в тексте нет претензии
к УК или к общедомовому хозяйству (охрана, камеры, домофон, лифт, дверь подъезда…), это не срочно для PR УК: P3, в отчёт.
Тот же вывод модели («зона ответственности — полиция/соседи/город») понижает только при тех же условиях — модель может
ошибиться, текст проверяется всегда.
"""
from __future__ import annotations

import re

# Происшествия, которыми занимаются полиция и охрана, а не УК/PR (если в тексте нет претензии к УК, охране, камерам…)
CRIME_RE = re.compile(r"полици|нападени|напал|драк|избил|избит|разбит\w* голов|голов\w* разбит|в крови|кров[ьи]\b|пистолет|"
                      r"оружи|\bнож\b|ножом|стрельб|стрелял|ограб|кража|украл|\bвор\b|воры|труп|убий|убит|наркот|закладк|"
                      r"неадекват|подозрительн\w* (?:мужчин|человек|женщин|тип)|маньяк|педофил|домогал|приставал|"
                      r"пропал\w* (?:ребен|реб[её]нок|человек|мужчин|женщин|подрост)|розыск", re.I)

# Претензия к УК или к тому, что УК обслуживает (общее имущество): тогда история «наша», даже если виноват хулиган
UK_DUTY_RE = re.compile(
    r"(?<![а-яё])ук(?![а-яё])|управляющ|управляйк|управляшк|консьерж|"
    r"охран\w*(?:\s+[\w«»\"]+){0,2}?\s+(?:не\s|нет|спит|отсутств|бездейств|ничего|молчит|игнорир)|"
    r"(?:куда|чем)\s+(?:\w+\s+)?(?:смотр|занима)\w*\s+(?:\w+\s+)?(?:охран|ук(?![а-яё])|управ|консьерж|застройщик)|"
    r"где\s+(?:же\s+|вообще\s+)?(?:охран|консьерж)|"
    r"камер\w* (?:видеонаблюдения )?(?:не |нет|сломан)|видеонаблюден|домофон|двер\w* не закрыва|замок сломан|диспетчер|"
    r"застройщик|освещени\w* нет|не горит свет|"
    # неисправность общего имущества — работа УК, кто бы её ни устроил («подростки сожгли кнопки, лифт стоит неделю»);
    # само место («у двери подъезда», «в лифте») претензией не считается
    r"лифт\w* (?:не работа|сломан|стоит|не ход|застр)|не работа\w* лифт|"
    r"двер\w* (?:в |)(?:подъезд|парадн)\w* (?:не закрыва|сломан|не работа|выбит|открыт\w* настежь)|"
    r"(?:просим|прошу|требуем|нужно|надо|пусть|почему не|когда)\s+(?:\w+\s+){0,3}(?:установ|постав)\w*\s+камер", re.I)

# Действия третьих лиц: хулиганство, вандализм, травля людей, конфликты соседей — зона полиции и самих жильцов
_PESTS = r"тарака|клоп|грызун|крыс|мыш|насеком|блох|муравь|комар"
THIRD_PARTY_RE = re.compile(
    r"хулиган\w*|вандал\w*|буллинг\w*|"
    # (?!\w) не даёт откатиться внутрь слова: иначе «травлю тараканов» ловилось как «травл» + «ю тараканов»
    rf"(?<![а-яё])травл\w*(?!\w)(?!\s+(?:\w+\s+)?(?:{_PESTS}))|(?<![а-яё])затравил\w*|"
    r"яйцами|(?:закидыва|забрасыва|закидал|забросал|кида|броса|швыря)\w*\s+(?:[\w«»\"]+\s+){0,4}яйц\w*|"
    r"(?:подрост|школьник|малолет|молод[её]ж|хулиган|компани\w+ молод)\w*[^.!?\n]{0,90}"
    r"(?:бьют|стучат|пинают|ломают|портят|поджига|подожгл|кидают|бросают|забрасыва|звонят в двер|орут|ор[её]т|"
    r"шумят|галдят|курят|распивают|мусорят|пугают|издеваются|убегают|разбивают|разрисов|исписал|исписыва)|"
    r"издева\w*\s+над\s+(?:пожил|пенсионер|стари|бабушк|дедушк|инвалид|реб[её]н|детьми|сосед|людьми)|"
    r"(?:конфликт|скандал|ссор|вражд)\w*\s+(?:\w+\s+)?с\s+сосед\w*|сосед\w*\s+(?:дебошир|скандал|угрожа|пьян|избил|бь[её]т)",
    re.I)

# Что модель может сказать в поле responsibility (brain/core.py) и что из этого «не УК»
RESPONSIBILITY = ["УК", "застройщик", "полиция", "жильцы_соседи", "власть_город", "не_определено"]
NOT_UK = {"полиция": "полиции", "жильцы_соседи": "самих жильцов", "власть_город": "города или района"}

# Адресаты, которые сами по себе делают историю «про УК»: жилищный надзор, лицензия
HOUSING_SUPERVISION = {"gzhi_spb", "gzhn_lo", "zhilkom_spb", "license"}


def uk_claim(body: str) -> bool:
    """В тексте есть претензия к УК или к общему имуществу дома."""
    return bool(UK_DUTY_RE.search(body or ""))


def third_party(body: str) -> str:
    """Короткая метка сюжета «действия третьих лиц» или ''."""
    m = THIRD_PARTY_RE.search(body or "")
    if not m:
        return ""
    w = m.group(0).lower()
    if "сосед" in w:
        return "конфликт соседей"
    if "травл" in w or "издева" in w or "затрав" in w or "буллинг" in w:
        return "травля людей"
    if "вандал" in w:
        return "вандализм"
    return "хулиганство"
